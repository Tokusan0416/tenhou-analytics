# 赤ドラの牌ID（各スーツの5の1枚目: ID=16,52,88）
RED_FIVES: set[int] = {16, 52, 88}


def tile_id_to_name(tile_id: int) -> str:
    """牌ID(0-135)を牌名に変換。赤ドラは'0m','0p','0s'で表記。"""
    if tile_id in RED_FIVES:
        suit = {16: "0m", 52: "0p", 88: "0s"}
        return suit[tile_id]
    return TILE_TYPES[tile_id // 4]


