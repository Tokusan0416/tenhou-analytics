# GO type ビットフラグ解析
GAME_TYPE_FLAGS: dict[str, int] = {
    "sanma": 0x10,  # 三人麻雀
    "tokutou": 0x00,  # 特東(東風戦) - デフォルト
    "tonnansen": 0x08,  # 東南戦
    "ippan": 0x00,  # 一般 - デフォルト
    "joukyuu": 0x01,  # 上級卓
    "tokujou": 0x02,  # 特上卓
    "houou": 0x04,  # 鳳凰卓
    "soku": 0x40,  # 速
    "no_red": 0x02,  # 赤なし(三麻時)
    "no_aka": 0x20,  # 赤なし(四麻時)
}


def parse_game_type(type_value: int) -> dict[str, str | bool]:
    """GOタグのtype値からゲーム種別情報を抽出。"""
    return {
        "is_sanma": bool(type_value & 0x10),
        "is_tonnansen": bool(type_value & 0x08),
        "is_soku": bool(type_value & 0x40),
        "is_no_red": bool(type_value & 0x20),
        "lobby": "鳳凰卓"
        if type_value & 0x04
        else "特上卓"
        if type_value & 0x02
        else "上級卓"
        if type_value & 0x01
        else "一般",
    }
